void main() {
  //Operator ! (NOT)
  bool Esteh = true;
  print(!Esteh);

  //Operator && (AND)
  bool Makan = true;
  bool Minum = false;

  print(Makan && Minum);
  print(Makan && true);

  //Operator || (OR)
  bool hariPuasa = false;
  bool tidurBrutal = true;

  print(hariPuasa || tidurBrutal);
  print(hariPuasa || false);
}
